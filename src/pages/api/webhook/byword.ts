import type { APIRoute } from "astro";

// On-demand Vercel function — receives Byword.ai's publish webhook (routed through
// Zapier/Make, since Byword itself only integrates natively with WP/Webflow/etc.),
// then opens a PR adding the article as a new guide. Nothing publishes automatically —
// see site plan §7: a human reviews the PR (Vercel gives it a preview deploy) before merging.
export const prerender = false;

const OWNER = "LockesteadVentures";
const REPO = "arizonapigeonproofing";
const GITHUB_API = "https://api.github.com";

interface BywordPayload {
  title?: string;
  description?: string;
  body?: string; // markdown content
  slug?: string;
  publishDate?: string;
}

function slugify(input: string) {
  return input
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
}

function ghHeaders(token: string) {
  return {
    Authorization: `Bearer ${token}`,
    Accept: "application/vnd.github+json",
    "Content-Type": "application/json",
  };
}

export const POST: APIRoute = async ({ request }) => {
  const secret = import.meta.env.BYWORD_WEBHOOK_SECRET;
  const provided = request.headers.get("x-webhook-secret");
  if (!secret || provided !== secret) {
    return new Response(JSON.stringify({ ok: false, error: "Unauthorized" }), { status: 401 });
  }

  const token = import.meta.env.GITHUB_TOKEN;
  if (!token) {
    console.error("Byword webhook missing GITHUB_TOKEN");
    return new Response(JSON.stringify({ ok: false, error: "Pipeline isn't configured yet." }), {
      status: 500,
    });
  }

  let payload: BywordPayload;
  try {
    payload = await request.json();
  } catch {
    return new Response(JSON.stringify({ ok: false, error: "Invalid request body" }), { status: 400 });
  }

  const { title, description, body } = payload;
  if (!title?.trim() || !description?.trim() || !body?.trim()) {
    return new Response(
      JSON.stringify({ ok: false, error: "title, description, and body are required." }),
      { status: 400 }
    );
  }

  const slug = payload.slug ? slugify(payload.slug) : slugify(title);
  const publishDate = payload.publishDate ?? new Date().toISOString().slice(0, 10);
  const branch = `content/${slug}`;
  const path = `src/data/guides/${slug}.md`;

  const fileContent = `---
title: "${title.replace(/"/g, '\\"')}"
description: "${description.replace(/"/g, '\\"')}"
publishDate: ${publishDate}
draft: false
---

${body}
`;

  try {
    // 1. Get main's current SHA
    const refRes = await fetch(`${GITHUB_API}/repos/${OWNER}/${REPO}/git/ref/heads/main`, {
      headers: ghHeaders(token),
    });
    if (!refRes.ok) throw new Error(`Could not read main ref: ${refRes.status}`);
    const refData = await refRes.json();
    const mainSha = refData.object.sha;

    // 2. Create a branch for this piece of content
    const branchRes = await fetch(`${GITHUB_API}/repos/${OWNER}/${REPO}/git/refs`, {
      method: "POST",
      headers: ghHeaders(token),
      body: JSON.stringify({ ref: `refs/heads/${branch}`, sha: mainSha }),
    });
    if (!branchRes.ok && branchRes.status !== 422) {
      // 422 = branch already exists, fine to proceed (e.g. a retry)
      throw new Error(`Could not create branch: ${branchRes.status}`);
    }

    // 3. Commit the new guide file to that branch
    const fileRes = await fetch(
      `${GITHUB_API}/repos/${OWNER}/${REPO}/contents/${path}`,
      {
        method: "PUT",
        headers: ghHeaders(token),
        body: JSON.stringify({
          message: `Add guide: ${title}`,
          content: Buffer.from(fileContent, "utf-8").toString("base64"),
          branch,
        }),
      }
    );
    if (!fileRes.ok) throw new Error(`Could not commit file: ${fileRes.status}`);

    // 4. Open a PR so a human reviews before it ever goes live
    const prRes = await fetch(`${GITHUB_API}/repos/${OWNER}/${REPO}/pulls`, {
      method: "POST",
      headers: ghHeaders(token),
      body: JSON.stringify({
        title: `New guide: ${title}`,
        head: branch,
        base: "main",
        body: `Auto-generated by the Byword.ai pipeline. Review the content, check it against real local specifics, then merge — merging deploys it live.\n\n**Description:** ${description}`,
      }),
    });
    if (!prRes.ok) throw new Error(`Could not open PR: ${prRes.status}`);
    const prData = await prRes.json();

    return new Response(JSON.stringify({ ok: true, prUrl: prData.html_url }), { status: 200 });
  } catch (err) {
    console.error("Byword webhook failed", err);
    return new Response(JSON.stringify({ ok: false, error: "Could not create content PR." }), {
      status: 502,
    });
  }
};
